import { webkit, devices, expect } from "@playwright/test";
import assert from "node:assert/strict";
import { mkdir } from "node:fs/promises";

const base = process.env.TEST_URL || "http://localhost:3000";
await mkdir("artifacts", { recursive: true });
const browser = await webkit.launch();
const context = await browser.newContext({ ...devices["iPhone 13"], viewport: { width: 390, height: 844 }, reducedMotion: "reduce", locale: "vi-VN" });
await context.addInitScript(() => Object.defineProperty(navigator, "standalone", { get: () => true, configurable: true }));
const page = await context.newPage();
const errors = [];
page.on("pageerror", (error) => errors.push(error.message));
await page.goto(`${base}/?view=overview&source=pwa`, { waitUntil: "networkidle" });
await expect(page.locator(".app-shell")).toHaveAttribute("data-app-mode", "standalone");
await expect(page.locator(".mobile-tabbar")).toBeVisible();
await expect(page.locator(".pwa-install-banner")).toHaveCount(0);
assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
await page.screenshot({ path: "artifacts/webkit-iphone-home.png" });
await page.getByRole("button", { name: "Tạo nhanh nội dung", exact: true }).click();
await page.getByRole("dialog").getByRole("button", { name: /Lên kế hoạch nội dung/ }).click();
await page.getByLabel("Tiêu đề nội dung").fill("Kiểm thử bàn phím WebKit");
assert.equal(await page.getByLabel("Tiêu đề nội dung").evaluate((element) => getComputedStyle(element).fontSize), "16px");
assert.equal(await page.locator(".modal").evaluate((element) => element.scrollWidth > element.clientWidth), false);
await page.getByRole("button", { name: "Đóng hộp thoại", exact: true }).click();
await page.getByRole("button", { name: "Mở lịch nội dung", exact: true }).click();
await page.getByRole("button", { name: "Xem lịch", exact: true }).click();
assert.equal(await page.locator(".calendar-card").evaluate((element) => element.scrollWidth > element.clientWidth), false);
await page.setViewportSize({ width: 844, height: 390 });
await page.waitForTimeout(300);
assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false, "landscape avoids notch-side overflow");
await expect(page.locator(".mobile-tabbar")).toBeVisible();
await page.setViewportSize({ width: 390, height: 844 });
await page.getByRole("button", { name: "Mở kết nối kênh", exact: true }).click();
await page.evaluate(() => { document.documentElement.style.setProperty("--safe-top", "47px"); document.documentElement.style.setProperty("--safe-bottom", "34px"); });
await page.waitForTimeout(150);
assert.equal(await page.locator(".mobile-tabbar").evaluate((element) => getComputedStyle(element).paddingBottom), "34px", "bottom safe-area padding is applied");
await page.screenshot({ path: "artifacts/webkit-iphone-safe-area.png" });
assert.deepEqual(errors, []);
await browser.close();
console.log("PASS: WebKit iPhone layout, standalone shell, touch navigation, 16px form inputs, portrait/landscape calendar, and simulated safe-area spacing. Actual Home Screen installation requires a physical iPhone.");
