import assert from "node:assert/strict";
import { chromium, expect } from "@playwright/test";
import AxeBuilder from "@axe-core/playwright";
import { readFile, mkdir } from "node:fs/promises";

const base = process.env.TEST_URL || "http://localhost:3000";
await mkdir("artifacts", { recursive: true });
const proxied = await fetch(`${base}/api/workspace`, { headers: { "x-forwarded-proto": "https" } });
assert.equal(proxied.status, 200);
assert.match(proxied.headers.get("set-cookie"), /;\s*Secure(?:;|$)/i, "forwarded HTTPS marks session cookie Secure");
assert.match(proxied.headers.get("set-cookie"), /HttpOnly/i);
const browser = await chromium.launch({ args: ["--no-sandbox"] });
const context = await browser.newContext({ viewport: { width: 1280, height: 1000 }, reducedMotion: "reduce", acceptDownloads: true });
const page = await context.newPage();
const errors = [];
const hmrSockets = [];
const developmentNotices = [];
page.on("pageerror", (error) => errors.push(error.message));
page.on("websocket", (socket) => { if (socket.url().includes("/_next/hmr")) hmrSockets.push(socket.url()); });
page.on("console", (message) => { if (message.text().includes("Download the React DevTools")) developmentNotices.push(message.text()); });
await page.goto(`${base}/?view=settings&diagnostics=1`, { waitUntil: "networkidle" });
const panel = page.locator(".deployment-diagnostics");
await expect(panel.locator(".diagnostic-result-title")).toContainText("10/10");
await expect(panel.locator(".diagnostic-resource-list li.failed")).toHaveCount(0);
await expect(panel.locator(".diagnostic-context")).toContainText("Production");
await expect(panel.locator(".diagnostic-summary")).toContainText("đang hoạt động");
await expect(panel.locator(".diagnostic-callback")).toContainText("/api/youtube/callback");
const healthyConfig = await (await context.request.get(`${base}/api/config`)).json();
assert.equal(healthyConfig.runtimeMode, "production");
await page.screenshot({ path: "artifacts/tunnel-diagnostics.png", fullPage: true });
const reportEvent = page.waitForEvent("download");
await panel.getByRole("button", { name: "Tải báo cáo không có secret", exact: true }).click();
const reportDownload = await reportEvent;
const report = JSON.parse(await readFile(await reportDownload.path(), "utf8"));
assert.equal(report.resources.length, 10);
assert.ok(!Object.hasOwn(report, "clientSecret"));
assert.ok(!Object.hasOwn(report, "checks"));
assert.ok(!JSON.stringify(report).includes("encryptedTokens"));

await page.route("**/icons/icon-192.png?tubeflow-check=*", (route) => route.fulfill({ status: 404, contentType: "text/plain", body: "not found" }));
await panel.getByRole("button", { name: "Kiểm tra font, icon & máy chủ", exact: true }).click();
await expect(panel.locator(".diagnostic-resource-list li.failed")).toHaveCount(1);
await expect(panel.locator(".diagnostic-resource-list li.failed")).toContainText("404");
await page.unroute("**/icons/icon-192.png?tubeflow-check=*");
await page.route("**/icons/icon-192.png?tubeflow-check=*", (route) => route.fulfill({ status: 200, contentType: "text/html", body: "<html>This is not an icon</html>" }));
await panel.getByRole("button", { name: "Kiểm tra font, icon & máy chủ", exact: true }).click();
await expect(panel.locator(".diagnostic-resource-list li.failed")).toContainText("200 nhưng");
await page.unroute("**/icons/icon-192.png?tubeflow-check=*");
await page.route("**/api/config", (route) => route.fulfill({ json: { ...healthyConfig, runtimeMode: "development" } }));
await panel.getByRole("button", { name: "Kiểm tra font, icon & máy chủ", exact: true }).click();
await expect(panel.locator(".diagnostic-context")).toContainText("Development");
await expect(panel).toContainText("không phải kết nối YouTube");
await page.unroute("**/api/config");
await panel.getByRole("button", { name: "Kiểm tra font, icon & máy chủ", exact: true }).click();
await expect(panel.locator(".diagnostic-result-title")).toContainText("10/10");
await page.setViewportSize({ width: 390, height: 844 });
assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
const audit = await new AxeBuilder({ page }).withTags(["wcag2a", "wcag2aa", "wcag21aa"]).analyze();
assert.deepEqual(audit.violations.map((item) => ({ id: item.id, targets: item.nodes.map((node) => node.target) })), []);
const originalWorkspace = await (await context.request.get(`${base}/api/workspace`)).json();
await context.request.patch(`${base}/api/workspace`, { data: { name: "Không gian chẩn đoán thử nghiệm" } });
const cookieBefore = (await context.cookies()).find((cookie) => cookie.name === "tubeflow_workspace").value;
const plan = await (await context.request.post(`${base}/api/plans`, { data: { title: "Giữ kế hoạch khi làm mới PWA", description: "Test only", format: "video", status: "idea", scheduledDate: null } })).json();
await page.evaluate(async () => {
  localStorage.setItem("tubeflow-test-preserve", "keep");
  await (await caches.open("unrelated-test-cache")).put("/unrelated-test-resource", new Response("keep"));
  await (await caches.open("tubeflow-test-old-cache")).put("/old-static-test-resource", new Response("old"));
});
await panel.getByRole("button", { name: "Làm mới cache PWA", exact: true }).click();
await expect(page.getByRole("dialog")).toContainText("Không xóa cookie");
await Promise.all([page.waitForNavigation({ waitUntil: "networkidle" }), page.getByRole("button", { name: "Làm mới và tải lại", exact: true }).click()]);
const cookieAfter = (await context.cookies()).find((cookie) => cookie.name === "tubeflow_workspace").value;
assert.equal(cookieAfter, cookieBefore, "PWA cache reset preserves the workspace cookie");
const restored = await (await context.request.get(`${base}/api/workspace`)).json();
assert.equal(restored.name, "Không gian chẩn đoán thử nghiệm");
assert.ok(restored.plans.some((item) => item.id === plan.id));
const storage = await page.evaluate(async () => ({ value: localStorage.getItem("tubeflow-test-preserve"), caches: await caches.keys() }));
assert.equal(storage.value, "keep");
assert.ok(storage.caches.includes("unrelated-test-cache"));
assert.ok(!storage.caches.includes("tubeflow-test-old-cache"));
await context.request.delete(`${base}/api/plans/${plan.id}`);
await context.request.patch(`${base}/api/workspace`, { data: { name: originalWorkspace.name } });
await page.goto(`${base}/?guide=1`, { waitUntil: "networkidle" });
const guide = page.getByRole("dialog");
await guide.getByRole("button", { name: /Ứng dụng đang triển khai/ }).click();
await page.getByLabel("URL gốc của ứng dụng").fill("https://diagnostic-test.trycloudflare.com");
await guide.locator(".walk-navigation button").nth(3).click();
await page.getByLabel("Nơi bạn quản lý triển khai").selectOption("cloudflare");
await expect(guide.locator(".walk-provider")).toContainText("máy đang chạy Next.js");
await guide.locator(".walk-navigation button").nth(4).click();
await expect(guide.locator(".walk-command-list")).toContainText("npm run build");
await expect(guide.locator(".walk-command-list")).toContainText("cloudflared tunnel --url http://127.0.0.1:3000");
await expect(guide.locator(".walk-command-list")).not.toContainText("npm run dev");
assert.deepEqual(hmrSockets, [], "production never opens the development HMR socket");
assert.deepEqual(developmentNotices, [], "production does not emit the React DevTools development notice");
assert.deepEqual(errors, []);
await browser.close();
console.log("PASS: forwarded HTTPS cookies, live asset diagnostics, 404/invalid-image detection, sanitized report, Cloudflare guidance, production without HMR, mobile accessibility, and cache reset without losing cookies or plans.");
