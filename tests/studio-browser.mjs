import { chromium, expect } from "@playwright/test";
import AxeBuilder from "@axe-core/playwright";
import assert from "node:assert/strict";
import { mkdir } from "node:fs/promises";

const base = process.env.TEST_URL || "http://localhost:3000";
await mkdir("artifacts", { recursive: true });
const browser = await chromium.launch({ args: ["--no-sandbox"] });
const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, reducedMotion: "reduce" });
const page = await context.newPage();
const errors = [];
page.on("pageerror", (error) => errors.push(error.message));
await page.goto(`${base}/?view=studio`, { waitUntil: "networkidle" });
await expect(page.getByRole("heading", { name: "YouTube Studio." })).toBeVisible();
await expect(page.getByRole("heading", { name: "Kết nối kênh để mở Studio" })).toBeVisible();
await page.getByRole("button", { name: "Kết nối kênh YouTube", exact: true }).click();
await expect(page.getByRole("heading", { name: "Kết nối kênh." })).toBeVisible();
await page.locator(".sidebar .nav-item").filter({ hasText: "YouTube Studio" }).click();
await expect(page.getByRole("heading", { name: "YouTube Studio." })).toBeVisible();
const audit = await new AxeBuilder({ page }).withTags(["wcag2a", "wcag2aa", "wcag21aa"]).analyze();
assert.deepEqual(audit.violations.map((item) => ({ id: item.id, targets: item.nodes.map((node) => node.target) })), []);
await page.screenshot({ path: "artifacts/studio-connect.png", fullPage: true });
await page.setViewportSize({ width: 390, height: 844 });
await page.getByRole("button", { name: "Mở điều hướng", exact: true }).click();
await page.locator(".sidebar .nav-item").filter({ hasText: "YouTube Studio" }).click();
await expect(page.getByRole("heading", { name: "YouTube Studio." })).toBeVisible();
assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false, "mobile studio has no horizontal overflow");
await page.screenshot({ path: "artifacts/studio-mobile.png", fullPage: true });
assert.deepEqual(errors, []);
await browser.close();
console.log("PASS: YouTube Studio navigation, unconnected prompt, desktop and mobile layout, and accessibility.");
