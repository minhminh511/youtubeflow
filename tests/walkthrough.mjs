import { chromium, expect } from "@playwright/test";
import AxeBuilder from "@axe-core/playwright";
import assert from "node:assert/strict";
import { mkdir, readFile } from "node:fs/promises";

const base = process.env.TEST_URL || "http://localhost:3000";
await mkdir("artifacts", { recursive: true });
const browser = await chromium.launch({ args: ["--no-sandbox"] });
const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, reducedMotion: "reduce", permissions: ["clipboard-read", "clipboard-write"], acceptDownloads: true });
const page = await context.newPage();
const runtimeErrors = [];
const mutations = [];
page.on("pageerror", (error) => runtimeErrors.push(error.message));
page.on("request", (request) => { if (["POST", "PATCH"].includes(request.method())) mutations.push(request.postData() || ""); });
let audits = 0;
async function accessible(label) {
  const result = await new AxeBuilder({ page }).withTags(["wcag2a", "wcag2aa", "wcag21aa"]).analyze();
  assert.deepEqual(result.violations.map((item) => ({ id: item.id, nodes: item.nodes.map((node) => node.target) })), [], `${label} accessibility`);
  audits++;
}
await page.goto(`${base}/?guide=1`, { waitUntil: "networkidle" });
const dialog = page.getByRole("dialog");
await expect(dialog.getByRole("heading", { name: "Cùng bạn kết nối YouTube" })).toBeVisible();
assert.equal(new URL(page.url()).searchParams.has("guide"), false, "deep-link flag is consumed without repeated opening");
await dialog.getByRole("button", { name: /Ứng dụng đang triển khai/ }).click();
await page.getByLabel("URL gốc của ứng dụng").fill("http://not-local.example.com");
await expect(dialog.getByRole("button", { name: "Tiếp tục", exact: true })).toBeDisabled();
await page.getByLabel("URL gốc của ứng dụng").fill("https://creator.example.com/extra-path");
await expect(dialog.getByRole("button", { name: "Tiếp tục", exact: true })).toBeDisabled();
await page.getByLabel("URL gốc của ứng dụng").fill("https://creator.example.com");
await expect(dialog.locator(".walk-value code")).toHaveText("https://creator.example.com/api/youtube/callback");
await dialog.getByRole("button", { name: "Sao chép URI cho Google Cloud", exact: true }).click();
assert.equal(await page.evaluate(() => navigator.clipboard.readText()), "https://creator.example.com/api/youtube/callback");
await accessible("Choose deployment URL");
await page.screenshot({ path: "artifacts/walkthrough-desktop.png" });
await dialog.getByRole("button", { name: "Tiếp tục", exact: true }).click();
await expect(dialog.getByRole("heading", { name: "Tạo dự án và bật hai API" })).toBeVisible();
await expect(dialog.getByRole("button", { name: "Lưu xác nhận & tiếp tục" })).toBeDisabled();
await expect(dialog.locator('a[href="https://console.cloud.google.com/apis/library/youtube.googleapis.com"]')).toBeVisible();
await page.getByLabel("Tôi đã thấy Data API v3 ở trạng thái được bật.").check();
await page.getByLabel("Tôi đã thấy Analytics API ở trạng thái được bật.").check();
await accessible("Enable APIs");
await dialog.getByRole("button", { name: "Lưu xác nhận & tiếp tục" }).click();
await expect(dialog.getByRole("heading", { name: "Tạo Client ID và Client Secret" })).toBeVisible();
await expect(dialog.locator(".walk-value code")).toHaveText("https://creator.example.com/api/youtube/callback");
await page.getByLabel("Tôi đã tạo Web application, lưu Client ID/Secret và thêm đúng redirect URI.").check();
await accessible("Create OAuth Client");
await dialog.getByRole("button", { name: "Lưu xác nhận & tiếp tục" }).click();
await expect(dialog.getByRole("heading", { name: "Điền bốn biến vào đúng nơi" })).toBeVisible();
const workspace = await (await context.request.get(`${base}/api/workspace`)).json();
assert.deepEqual(workspace.completedSteps, [1, 2, 4], "manual confirmations persist separately from server verification");
await page.getByLabel("Nơi bạn quản lý triển khai").selectOption("vercel");
await expect(dialog.locator(".walk-provider")).toContainText("Environment Variables");
await dialog.getByRole("button", { name: "Tạo khóa 64 ký tự", exact: true }).click();
const secret = await dialog.locator(".walk-value code").filter({ hasText: /^[a-f0-9]{64}$/ }).textContent();
assert.match(secret, /^[a-f0-9]{64}$/);
const downloadEvent = page.waitForEvent("download");
await dialog.getByRole("button", { name: "Tải checklist cho người triển khai", exact: true }).click();
const download = await downloadEvent;
const handoff = await readFile(await download.path(), "utf8");
assert.ok(handoff.includes("https://creator.example.com/api/youtube/callback"));
assert.ok(!handoff.includes(secret), "deployer checklist never contains the generated secret");
await dialog.locator(".walk-template summary").click();
await expect(dialog.locator(".walk-code pre")).toContainText("GOOGLE_CLIENT_ID=\nGOOGLE_CLIENT_SECRET=\n");
await expect(dialog.locator(".walk-code pre")).toContainText(`YOUTUBE_TOKEN_SECRET=${secret}`);
await accessible("Server environment and secret generation");
await dialog.getByRole("button", { name: "Xem cách chạy lại", exact: true }).click();
await expect(dialog.locator(".walk-task-list")).toContainText("Deployments");
await expect(dialog.getByRole("button", { name: "Kết nối kênh", exact: true })).toBeDisabled();
await dialog.getByRole("button", { name: "Kiểm tra máy chủ ngay", exact: true }).click();
await expect(dialog.locator(".walk-check-result")).toContainText("Còn 4 biến");
await expect(dialog.locator(".walk-server-check")).toContainText("đang hoạt động");
await expect(dialog.locator(".walk-check-warning").first()).toContainText("không phải");
await accessible("Actual server verification");
assert.ok(mutations.every((body) => !body.includes(secret)), "generated secret is never posted to the server");
const configuration = await (await context.request.get(`${base}/api/config`)).json();
assert.equal(configuration.ready, false, "visiting walkthrough does not configure real environment variables");
await dialog.locator(".walk-navigation button").nth(0).click();
await dialog.getByRole("button", { name: /Chạy trên máy cá nhân/ }).click();
await expect(page.getByLabel("URL gốc của ứng dụng")).toHaveValue("http://localhost:3000");
await dialog.locator(".walk-navigation button").nth(4).click();
await expect(dialog.locator(".walk-command-list code")).toHaveText(["npm install", "npx drizzle-kit push", "npm run dev"]);
await accessible("Local run commands");
await dialog.getByRole("button", { name: "Đóng hộp thoại", exact: true }).click();
await page.reload({ waitUntil: "networkidle" });
await expect(page.locator("#setup-guide")).toHaveCount(0);
const persisted = await (await context.request.get(`${base}/api/workspace`)).json();
assert.deepEqual(persisted.completedSteps, [1, 2, 4], "saved confirmations persist after reload");
for (const step of [1, 2, 4]) await context.request.patch(`${base}/api/setup`, { data: { step, completed: false } });
await page.setViewportSize({ width: 390, height: 844 });
await page.getByRole("button", { name: "Mở điều hướng", exact: true }).click();
await page.getByRole("button", { name: /Khám phá hướng dẫn/ }).click();
await expect(page.getByRole("dialog")).toBeVisible();
assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false, "no mobile document overflow");
assert.equal(await page.locator(".modal").evaluate((element) => element.scrollWidth > element.clientWidth), false, "no mobile dialog overflow");
await accessible("Mobile guided setup");
await page.screenshot({ path: "artifacts/walkthrough-mobile.png" });
await page.keyboard.press("Escape");
await expect(page.getByRole("dialog")).toBeHidden();
assert.deepEqual(runtimeErrors, []);
await browser.close();
console.log(`PASS: guided setup, valid redirect URLs, explicit saved confirmations, private key generation, sanitized handoff, real server checks, local commands, mobile layout, and ${audits} accessibility states.`);
