import { chromium, expect } from "@playwright/test";
import AxeBuilder from "@axe-core/playwright";
import assert from "node:assert/strict";
import { mkdir, writeFile } from "node:fs/promises";
import sharp from "sharp";

const base = process.env.TEST_URL || "http://localhost:3000";
await mkdir("artifacts", { recursive: true });
const browser = await chromium.launch({ args: ["--no-sandbox"] });
const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, reducedMotion: "reduce", acceptDownloads: true });
const page = await context.newPage();
const errors = [];
page.on("pageerror", (error) => errors.push(error.message));
await page.goto(`${base}/?view=editor`, { waitUntil: "networkidle" });
await expect(page.getByRole("heading", { name: "Edit Video/Image." })).toBeVisible();
await expect(page.getByRole("button", { name: "Nhập file", exact: true }).first()).toBeVisible();

const imagePath = "artifacts/test-edit.png";
await sharp({ create: { width: 640, height: 480, channels: 3, background: { r: 90, g: 140, b: 220 } } }).png().toFile(imagePath);
await page.locator('input[type="file"]').setInputFiles(imagePath);
await expect(page.locator(".editor-media-item strong")).toHaveText("test-edit.png");
await expect(page.locator(".editor-canvas")).toBeVisible();
const canvasSize = await page.locator(".editor-canvas").evaluate((canvas) => ({ width: canvas.width, height: canvas.height }));
assert.ok(canvasSize.width > 0 && canvasSize.height > 0, "canvas renders the imported image");
await page.getByRole("tab", { name: "Bộ lọc" }).click();
await page.getByRole("button", { name: "Rực rỡ", exact: true }).click();
await page.getByRole("tab", { name: "Điều chỉnh" }).click();
await page.locator(".editor-slider input[type=range]").first().fill("30");
await page.getByRole("tab", { name: "Chữ" }).click();
await page.getByLabel("Nội dung chữ").fill("Xin chào TubeFlow");
await page.getByRole("tab", { name: "Xoay & Cắt" }).click();
await page.getByLabel("Tỷ lệ cắt").selectOption("1:1");
await page.waitForTimeout(300);
const cropped = await page.locator(".editor-canvas").evaluate((canvas) => ({ width: canvas.width, height: canvas.height }));
assert.equal(cropped.width, cropped.height, "1:1 crop makes the canvas square");
const downloadEvent = page.waitForEvent("download");
await page.getByRole("button", { name: "Tải xuống", exact: true }).click();
const download = await downloadEvent;
assert.equal(download.suggestedFilename(), "tubeflow-edit.png");
const audit = await new AxeBuilder({ page }).withTags(["wcag2a", "wcag2aa", "wcag21aa"]).analyze();
assert.deepEqual(audit.violations.map((item) => ({ id: item.id, targets: item.nodes.map((node) => node.target) })), []);
await page.screenshot({ path: "artifacts/editor-desktop.png", fullPage: true });
await page.setViewportSize({ width: 390, height: 844 });
await page.waitForTimeout(300);
assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false, "mobile editor has no horizontal overflow");
await expect(page.locator(".editor-canvas")).toBeVisible();
await page.screenshot({ path: "artifacts/editor-mobile.png", fullPage: true });
assert.deepEqual(errors, []);
await browser.close();
console.log("PASS: editor import, filters, adjustments, text, crop, PNG export, mobile layout, and accessibility.");
