import { chromium, expect } from "@playwright/test";
import AxeBuilder from "@axe-core/playwright";
import assert from "node:assert/strict";
import { mkdir } from "node:fs/promises";

const base = process.env.TEST_URL || "http://localhost:3000";
await mkdir("artifacts", { recursive: true });
const browser = await chromium.launch({ args: ["--no-sandbox"] });
const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, reducedMotion: "reduce" });
const page = await context.newPage();
const errors = [];
page.on("pageerror", (error) => errors.push(error.message));
await page.goto(`${base}/?view=strategy`, { waitUntil: "networkidle" });
await expect(page.getByRole("heading", { name: "Ý tưởng & chiến lược." })).toBeVisible();
await page.getByRole("button", { name: "Tạo gợi ý video", exact: true }).first().click();
await expect(page.locator(".strategy-idea-grid .idea-card").first()).toBeVisible();
await page.locator(".sidebar .nav-item").filter({ hasText: "Ý tưởng & chiến lược" }).click();
await page.getByRole("tab", { name: /Trụ cột nội dung/ }).click();
await page.getByRole("button", { name: "Thêm trụ cột đầu tiên", exact: true }).click();
await page.getByLabel("Tên trụ cột").fill("Mẹo quay phim");
await page.getByLabel("Mô tả").fill("Kỹ thuật quay bằng điện thoại");
await page.getByRole("button", { name: "Lưu trụ cột", exact: true }).click();
await expect(page.locator(".strategy-pillar-card h3")).toHaveText("Mẹo quay phim");
await page.getByRole("tab", { name: /Đối thủ/ }).click();
await expect(page.getByRole("heading", { name: "Theo dõi đối thủ" })).toBeVisible();
await page.locator(".sidebar .nav-item").filter({ hasText: /^Kiếm tiền$/ }).click();
await expect(page.getByRole("heading", { name: "Kiếm tiền." })).toBeVisible();
await expect(page.getByRole("heading", { name: "Kết nối kênh để theo dõi tiến độ" })).toBeVisible();
await page.getByRole("button", { name: "Ghi doanh thu", exact: true }).click();
await page.getByLabel("Số tiền (VNĐ)").fill("2500000");
await page.getByRole("button", { name: "Lưu doanh thu", exact: true }).click();
await expect(page.locator(".monetization-entry strong")).toHaveText("2.500.000 VNĐ");
const audit = await new AxeBuilder({ page }).withTags(["wcag2a", "wcag2aa", "wcag21aa"]).analyze();
assert.deepEqual(audit.violations.map((item) => ({ id: item.id, targets: item.nodes.map((node) => node.target) })), []);
await page.screenshot({ path: "artifacts/monetization.png", fullPage: true });
await page.setViewportSize({ width: 390, height: 844 });
await page.getByRole("button", { name: "Mở điều hướng", exact: true }).click();
await page.locator(".sidebar .nav-item").filter({ hasText: "Ý tưởng & chiến lược" }).click();
await expect(page.getByRole("heading", { name: "Ý tưởng & chiến lược." })).toBeVisible();
assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false, "mobile strategy has no horizontal overflow");
await page.screenshot({ path: "artifacts/strategy-mobile.png", fullPage: true });
assert.deepEqual(errors, []);
await browser.close();
console.log("PASS: strategy ideas, pillars, competitors tab, monetization prompt, revenue log, mobile layout, and accessibility.");
