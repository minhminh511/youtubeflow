import { chromium, expect } from "@playwright/test";
import assert from "node:assert/strict";
import { mkdir } from "node:fs/promises";

const base = process.env.TEST_URL || "http://localhost:3000";
await mkdir("artifacts", { recursive: true });
const browser = await chromium.launch({ headless: true, args: ["--no-sandbox"] });
const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, deviceScaleFactor: 1, permissions: ["clipboard-read", "clipboard-write"] });
const page = await context.newPage();
const errors = [];
page.on("pageerror", (error) => errors.push(error.message));
await page.goto(base, { waitUntil: "networkidle" });
await page.evaluate(() => document.fonts.ready);
await expect(page.getByRole("heading", { name: "Kết nối kênh." })).toBeVisible();
await page.screenshot({ path: "artifacts/desktop.png", fullPage: true });
await page.screenshot({ path: "artifacts/desktop-viewport.png" });
assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth), false, "desktop has no horizontal overflow");

await page.locator(".connect-button").click();
await expect(page.getByRole("dialog")).toBeVisible();
await expect(page.getByRole("heading", { name: "Một bước nhỏ trước khi kết nối" })).toBeVisible();
await page.getByRole("button", { name: "Xem hướng dẫn thiết lập" }).click();
const walkthrough = page.getByRole("dialog");
await expect(walkthrough.getByRole("heading", { name: "Cùng bạn kết nối YouTube" })).toBeVisible();
await walkthrough.getByRole("button", { name: /Ứng dụng đang triển khai/ }).click();
await page.getByLabel("URL gốc của ứng dụng").fill("https://creator.example.com");
await expect(walkthrough.locator(".walk-value code")).toHaveText("https://creator.example.com/api/youtube/callback");
await walkthrough.locator(".walk-navigation button").nth(1).click();
await page.getByLabel("Tôi đã thấy Data API v3 ở trạng thái được bật.").check();
await page.getByLabel("Tôi đã thấy Analytics API ở trạng thái được bật.").check();
await walkthrough.getByRole("button", { name: "Lưu xác nhận & tiếp tục" }).click();
await expect(walkthrough.getByRole("heading", { name: "Tạo Client ID và Client Secret" })).toBeVisible();
await walkthrough.locator(".walk-navigation button").nth(3).click();
await walkthrough.getByRole("button", { name: "Tạo khóa 64 ký tự", exact: true }).click();
const secret = await walkthrough.locator(".walk-value code").filter({ hasText: /^[a-f0-9]{64}$/ }).textContent();
assert.match(secret, /^[a-f0-9]{64}$/, "secret generated locally with 256-bit entropy");
await walkthrough.locator(".walk-template summary").click();
await expect(walkthrough.locator(".walk-code pre")).toContainText(`YOUTUBE_TOKEN_SECRET=${secret}`);
await walkthrough.getByRole("button", { name: "Sao chép mẫu hướng dẫn môi trường" }).click();
assert.match(await page.evaluate(() => navigator.clipboard.readText()), /GOOGLE_CLIENT_ID=/);
await walkthrough.getByRole("button", { name: "Đóng hộp thoại", exact: true }).click();
await page.locator(".check-config-button").click();
await expect(page.locator(".toast")).toContainText("Máy chủ còn 4 biến");
const workspaceAfterGuide = await (await context.request.get(`${base}/api/workspace`)).json();
assert.ok(workspaceAfterGuide.completedSteps.includes(1), "setup progress persists");
await context.request.patch(`${base}/api/setup`, { data: { step: 1, completed: false } });
const workspaceCleared = await (await context.request.get(`${base}/api/workspace`)).json();
assert.ok(!workspaceCleared.completedSteps.includes(1), "setup progress can be cleared");
await page.getByRole("tab", { name: "Quyền truy cập" }).click();
await expect(page.getByRole("heading", { name: "Kênh của bạn. Quyền kiểm soát của bạn." })).toBeVisible();

await page.locator(".sidebar .nav-item").filter({ hasText: "Lịch nội dung" }).click();
await page.getByRole("button", { name: "Tạo nội dung", exact: true }).click();
await page.getByLabel("Tiêu đề nội dung").fill("Nội dung kiểm thử giao diện");
await page.getByLabel("Ghi chú & kịch bản").fill("Dữ liệu thử nghiệm sẽ được xóa sau khi kiểm tra.");
await page.getByLabel("Định dạng", { exact: true }).selectOption("short");
await page.getByRole("button", { name: "Lưu nội dung", exact: true }).click();
await expect(page.getByRole("dialog")).toBeHidden();
await page.getByRole("button", { name: "Xem danh sách", exact: true }).click();
await expect(page.locator(".plan-title-button")).toHaveText("Nội dung kiểm thử giao diện");
await page.locator(".plan-title-button").click();
await page.getByLabel("Tiêu đề nội dung").fill("Ý tưởng kiểm thử đã chỉnh sửa");
await page.getByLabel("Trạng thái", { exact: true }).selectOption("idea");
await page.getByRole("button", { name: "Lưu nội dung", exact: true }).click();
await page.locator(".sidebar .nav-item").filter({ hasText: "Kho ý tưởng" }).click();
await expect(page.locator(".idea-card h3")).toHaveText("Ý tưởng kiểm thử đã chỉnh sửa");
await page.reload({ waitUntil: "networkidle" });
await expect(page.locator(".idea-card h3")).toHaveText("Ý tưởng kiểm thử đã chỉnh sửa");
await page.getByRole("button", { name: "Chỉnh sửa Ý tưởng kiểm thử đã chỉnh sửa" }).click();
await page.getByRole("button", { name: "Xóa", exact: true }).click();
await page.getByRole("button", { name: "Xóa nội dung", exact: true }).click();
await expect(page.locator(".idea-card")).toHaveCount(0);

await page.locator(".sidebar .nav-item").filter({ hasText: /^Cài đặt$/ }).click();
await page.getByLabel("Tên không gian", { exact: true }).fill("Góc sáng tạo kiểm thử");
await page.getByRole("button", { name: "Lưu thay đổi" }).click();
await expect(page.locator(".workspace-switcher strong")).toHaveText("Góc sáng tạo kiểm thử");
await page.reload({ waitUntil: "networkidle" });
await expect(page.getByLabel("Tên không gian", { exact: true })).toHaveValue("Góc sáng tạo kiểm thử");
await page.getByLabel("Tên không gian", { exact: true }).fill("Không gian của tôi");
await page.getByRole("button", { name: "Lưu thay đổi" }).click();
await page.getByRole("button", { name: "Trung tâm trợ giúp", exact: true }).click();
await page.getByRole("button", { name: "Câu hỏi thường gặp", exact: true }).click();
await expect(page.getByText("Lỗi 400: redirect_uri_mismatch", { exact: true })).toBeVisible();
await page.keyboard.press("Escape");
await expect(page.getByRole("dialog")).toBeHidden();

const mobile = await browser.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 1, isMobile: true, hasTouch: true });
const mobilePage = await mobile.newPage();
mobilePage.on("pageerror", (error) => errors.push(error.message));
await mobilePage.goto(base, { waitUntil: "networkidle" });
await mobilePage.evaluate(() => document.fonts.ready);
assert.equal(await mobilePage.evaluate(() => document.documentElement.scrollWidth > window.innerWidth), false, "mobile has no horizontal overflow");
await mobilePage.screenshot({ path: "artifacts/mobile.png", fullPage: true });
await mobilePage.screenshot({ path: "artifacts/mobile-viewport.png" });
await mobilePage.getByRole("button", { name: "Mở điều hướng", exact: true }).click();
await mobilePage.locator(".sidebar .nav-item").filter({ hasText: "Kho ý tưởng" }).click();
await expect(mobilePage.getByRole("heading", { name: "Kho ý tưởng." })).toBeVisible();
await expect(mobilePage.locator(".sidebar")).not.toHaveClass(/mobile-open/);
await mobilePage.getByRole("button", { name: "Thêm ý tưởng", exact: true }).click();
await expect(mobilePage.getByRole("dialog")).toBeVisible();
await mobilePage.getByRole("button", { name: "Đóng hộp thoại", exact: true }).click();
assert.deepEqual(errors, [], "no browser runtime errors");
await browser.close();
console.log("PASS: responsive layout, OAuth setup guard, secret generation, clipboard, configuration refresh, progress persistence, redirect builder, permissions tab, plan CRUD, idea persistence, workspace settings, FAQ, keyboard dismissal, and mobile navigation.");
