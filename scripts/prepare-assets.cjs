/* Restore portable public assets before Next dev/build. Never reads .env. */
const fs = require("node:fs/promises");
const path = require("node:path");
const crypto = require("node:crypto");
const sharp = require("sharp");

const PROJECT_ROOT = path.resolve(__dirname, "..");
const FONT_NAMES = ["inter-vietnamese.woff2", "inter-latin.woff2"];
const ICONS = [
  { file: "icons/icon-192.png", size: 192, maskable: false },
  { file: "icons/icon-512.png", size: 512, maskable: false },
  { file: "icons/maskable-512.png", size: 512, maskable: true },
  { file: "apple-touch-icon.png", size: 180, maskable: false },
];
const FONT_RANGES = {
  "inter-vietnamese.woff2": "U+0102-0103,U+0110-0111,U+0128-0129,U+0168-0169,U+01A0-01A1,U+01AF-01B0,U+0300-0301,U+0303-0304,U+0308-0309,U+0323,U+0329,U+1EA0-1EF9,U+20AB",
  "inter-latin.woff2": "U+0000-00FF,U+0131,U+0152-0153,U+02BB-02BC,U+02C6,U+02DA,U+02DC,U+0304,U+0308,U+0329,U+2000-206F,U+2074,U+20AC,U+2122,U+2191,U+2193,U+2212,U+2215,U+FEFF,U+FFFD",
};

function validWoff2(bytes) {
  return bytes.length >= 48 && bytes.length <= 4 * 1024 * 1024 && bytes.subarray(0, 4).toString("ascii") === "wOF2" && bytes.readUInt32BE(8) === bytes.length;
}
async function readOrNull(file) { try { return await fs.readFile(file); } catch { return null; } }
async function writeIfChanged(file, content) {
  const bytes = Buffer.isBuffer(content) ? content : Buffer.from(content);
  const existing = await readOrNull(file);
  if (existing?.equals(bytes)) return false;
  await fs.mkdir(path.dirname(file), { recursive: true });
  await fs.writeFile(file, bytes);
  return true;
}
function iconSvg(maskable) {
  return `<svg xmlns="http://www.w3.org/2000/svg" width="512" height="512" viewBox="0 0 512 512"><defs><linearGradient id="bg" x1="0" y1="0" x2="1" y2="1"><stop stop-color="#9270e7"/><stop offset="1" stop-color="#6642c6"/></linearGradient><linearGradient id="shine" x1="0" y1="0" x2="0" y2="1"><stop stop-color="white" stop-opacity=".12"/><stop offset="1" stop-color="white" stop-opacity="0"/></linearGradient></defs><rect width="512" height="512" fill="url(#bg)"/><path d="M0 0h512v215Q256 306 0 162Z" fill="url(#shine)"/><g transform="translate(256 256) scale(${maskable ? 0.82 : 1}) translate(-256 -256)"><path d="M181 137c0-15 16-24 29-16l207 119c13 8 13 27 0 35L210 394c-13 8-29-1-29-16V137Z" fill="white"/><path d="m133 155 164 94c6 4 6 12 0 16l-164 94V155Z" fill="#b8a0f1"/></g></svg>`;
}
async function validPng(file, size) {
  try { const metadata = await sharp(file).metadata(); return metadata.format === "png" && metadata.width === size && metadata.height === size; }
  catch { return false; }
}

async function preparePublicAssets(options = {}) {
  const root = options.root || PROJECT_ROOT;
  const output = options.publicDir || path.join(root, "public");
  const fontsSource = options.fontsDir || path.join(root, "assets/fonts");
  const restored = [];
  const fonts = [];
  const warnings = [];
  let sourceManifest = { fonts: [] };
  try { sourceManifest = JSON.parse(await fs.readFile(path.join(fontsSource, "manifest.json"), "utf8")); } catch { /* Existing binary fonts can still be used. */ }
  for (const name of FONT_NAMES) {
    const target = path.join(output, "fonts", name);
    let bytes = await readOrNull(target);
    if (!bytes || !validWoff2(bytes)) {
      const source = await readOrNull(path.join(fontsSource, `${name}.base64`));
      const entry = sourceManifest.fonts?.find((item) => item.name === name);
      if (source && entry?.sha256) {
        const decoded = Buffer.from(source.toString("utf8").replace(/\s/g, ""), "base64");
        if (validWoff2(decoded) && crypto.createHash("sha256").update(decoded).digest("hex") === entry.sha256) {
          await writeIfChanged(target, decoded);
          restored.push(`fonts/${name}`);
          bytes = decoded;
        }
      }
    }
    if (bytes && validWoff2(bytes)) fonts.push(name);
    else warnings.push(`Không có nguồn font hợp lệ cho ${name}; dùng phông hệ thống, không tạo yêu cầu tới file thiếu.`);
  }
  const faces = ["/* TUBEFLOW_FONT_FACES: generated by scripts/prepare-assets.cjs; safe system-font fallback if absent. */"];
  for (const name of fonts) faces.push(`@font-face{font-family:Inter;font-style:normal;font-weight:100 900;font-display:swap;src:url('/fonts/${name}') format('woff2');unicode-range:${FONT_RANGES[name]}}`);
  await writeIfChanged(path.join(output, "fonts/font-faces.css"), faces.join("\n") + "\n");
  const license = await readOrNull(path.join(fontsSource, "OFL.txt"));
  if (license) await writeIfChanged(path.join(output, "fonts/OFL.txt"), license);
  for (const icon of ICONS) {
    const target = path.join(output, icon.file);
    if (await validPng(target, icon.size)) continue;
    const image = await sharp(Buffer.from(iconSvg(icon.maskable))).resize(icon.size, icon.size).png().toBuffer();
    await writeIfChanged(target, image);
    restored.push(icon.file);
  }
  return { restored, fonts, warnings };
}

async function checkPublicAssets(options = {}) {
  const output = options.publicDir || path.join(options.root || PROJECT_ROOT, "public");
  const items = [];
  for (const icon of ICONS) items.push({ path: `/${icon.file}`, ok: await validPng(path.join(output, icon.file), icon.size), description: `PNG ${icon.size}×${icon.size}` });
  for (const file of ["fonts/font-faces.css", "offline.html", "offline.css", "offline.js", "sw.js"]) {
    const data = await readOrNull(path.join(output, file));
    items.push({ path: `/${file}`, ok: !!data?.length, description: "Tài nguyên công khai" });
  }
  const faces = (await readOrNull(path.join(output, "fonts/font-faces.css")))?.toString("utf8") || "";
  for (const name of FONT_NAMES) {
    if (!faces.includes(`/fonts/${name}`)) continue;
    const bytes = await readOrNull(path.join(output, "fonts", name));
    items.push({ path: `/fonts/${name}`, ok: !!bytes && validWoff2(bytes), description: "WOFF2" });
  }
  return { ok: items.every((item) => item.ok), items, usesSystemFonts: !FONT_NAMES.some((name) => faces.includes(`/fonts/${name}`)) };
}

module.exports.preparePublicAssets = preparePublicAssets;
module.exports.checkPublicAssets = checkPublicAssets;
module.exports.validWoff2 = validWoff2;

if (require.main === module) {
  (async () => {
    if (!process.argv.includes("--check")) {
      const result = await preparePublicAssets();
      for (const name of result.restored) console.log(`[TubeFlow] Đã khôi phục public/${name}`);
      for (const warning of result.warnings) console.warn(`[TubeFlow] ${warning}`);
    }
    const result = await checkPublicAssets();
    for (const item of result.items) console.log(`${item.ok ? "OK" : "THIẾU / SAI"} ${item.path} — ${item.description}`);
    if (result.usesSystemFonts) console.log("INFO Đang dùng phông hệ thống; stylesheet không tham chiếu font thiếu.");
    if (!result.ok) {
      console.error("Hãy chạy node scripts/prepare-assets.cjs và kiểm tra bạn đã sao chép đủ public/. Nếu dùng standalone, cần chép cả public/ và .next/static/ vào thư mục chạy server.js.");
      process.exitCode = 1;
    }
  })().catch((error) => { console.error(`[TubeFlow] Không chuẩn bị được tài nguyên: ${error.message}`); process.exitCode = 1; });
}
